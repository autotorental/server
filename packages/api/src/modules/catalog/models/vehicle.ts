import { model } from "@medusajs/framework/utils"

export const Vehicle = model.define("vehicle", {
  id: model.id({ prefix: "veh" }).primaryKey(),
  seller_id: model.text().index(),
  brand_id: model.text().index(),
  model_id: model.text().index().nullable(),
  body_type_id: model.text().index().nullable(),
  city_id: model.text().index(),
  title: model.text(),
  slug: model.text().nullable(),
  description: model.text().nullable(),
  year: model.number().nullable(),
  mileage_km: model.number().nullable(),
  color: model.text().nullable(),
  vin: model.text().nullable(),
  fuel_type: model.enum(["petrol","diesel","electric","hybrid","plugin_hybrid","other"]).nullable(),
  transmission: model.enum(["automatic","manual","cvt","semi_automatic"]).nullable(),
  seats: model.number().nullable(),
  doors: model.number().nullable(),
  currency_code: model.text().default("aed"),
  daily_price: model.number().nullable(),
  weekly_price: model.number().nullable(),
  monthly_price: model.number().nullable(),
  security_deposit: model.number().nullable(),
  security_deposit_note: model.text().nullable(),
  // ── Promotion / discount fields ──
  sale_daily_price: model.number().nullable(),
  sale_weekly_price: model.number().nullable(),
  sale_monthly_price: model.number().nullable(),
  discount_percent: model.number().nullable(),     // 0-100, applied by frontend if sale prices not set
  discount_label: model.text().nullable(),         // "Summer Sale", "Eid Special", etc.
  discount_starts_at: model.dateTime().nullable(),
  discount_ends_at: model.dateTime().nullable(),
  // ── Contact ──
  phone_number: model.text().nullable(),
  whatsapp_number: model.text().nullable(),
  livekit_enabled: model.boolean().default(false),
  photos: model.json().nullable(),
  videos: model.json().nullable(),
  feature_ids: model.json().nullable(),
  status: model.enum(["draft","pending_approval","active","rejected","paused","rented","unavailable"]).default("pending_approval").index(),
  rejection_reason: model.enum(["wrong_details","photos_unclear","wrong_price","missing_info","duplicate","inappropriate","spam","fake","other"]).nullable(),
  rejection_note: model.text().nullable(),
  approved_at: model.dateTime().nullable(),
  rejected_at: model.dateTime().nullable(),
  is_featured: model.boolean().default(false),
  view_count: model.number().default(0),
})
