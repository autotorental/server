#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Auto to Rental — vendor custom-domain provisioner.
#
# For every seller.custom_domain in the DB whose DNS already points at this
# server, obtain a Let's Encrypt certificate (HTTP-01 / webroot) and write an
# nginx vhost that serves that company's page (companies/<handle>) over HTTPS.
# Reconciles removed domains (vendor disconnected) by deleting their vhost.
#
# SAFE BY DESIGN:
#   * only ever ADDS vhost files (prefix cd-) — never touches platform vhosts
#   * runs `nginx -t` after every change; reloads ONLY if the test passes,
#     otherwise reverts the change so the live config is never left broken
#   * idempotent — safe to run from cron every few minutes
#
# Status is written back to seller.custom_domain_status: live | error (the API
# sets pending|dns_ok). Run: scripts/provision-custom-domains.sh [--dry-run]
# ---------------------------------------------------------------------------
set -uo pipefail

SERVER_IP="76.13.184.134"
WEBROOT="/var/www/acme"
SITES="/etc/nginx/sites-enabled"
PREFIX="cd-"                       # our vhost files: cd-<domain>.conf
STOREFRONT="127.0.0.1:7100"
EMAIL="admin@autotorental.com"
LOG="/var/log/atr-custom-domains.log"
LOCK="/tmp/atr-provision-domains.lock"
DRY_RUN="${1:-}"

DBURL="$(grep -hoE 'postgres[a-z]*://[^ \"]+' /opt/autorental/packages/api/.env | head -1)"
log() { echo "[$(date '+%F %T')] $*" >>"$LOG"; echo "$*"; }
psqlq() { psql "$DBURL" -tAc "$1" 2>>"$LOG"; }

# Single instance only.
exec 9>"$LOCK"
if ! flock -n 9; then echo "another run in progress"; exit 0; fi

mkdir -p "$WEBROOT"
[ -z "$DBURL" ] && { log "FATAL: no DATABASE_URL"; exit 1; }

# Resolve A records via a public resolver (fresh, no local cache).
resolves_here() {  # $1 = host -> 0 if it points at SERVER_IP
  local ips
  ips="$(dig +short A "$1" @1.1.1.1 2>/dev/null)"
  [ -z "$ips" ] && ips="$(dig +short A "$1" 2>/dev/null)"
  echo "$ips" | grep -qx "$SERVER_IP"
}

nginx_apply() {  # reload nginx iff config tests OK; else caller reverts. returns 0/1
  if nginx -t >>"$LOG" 2>&1; then
    [ "$DRY_RUN" = "--dry-run" ] && { log "  (dry-run) would reload nginx"; return 0; }
    systemctl reload nginx >>"$LOG" 2>&1 && return 0
  fi
  return 1
}

write_vhost() {  # $1 domain  $2 handle
  local d="$1" h="$2" f="$SITES/${PREFIX}$1.conf"
  local hosts="$d" ; resolves_here "www.$d" && hosts="$d www.$d"
  cat >"$f" <<EOF
# ${PREFIX}$d.conf — generated by provision-custom-domains.sh. Do not edit.
server {
    listen 80;
    server_name $hosts;
    location ^~ /.well-known/acme-challenge/ { root $WEBROOT; default_type "text/plain"; try_files \$uri =404; }
    location / { return 301 https://$d\$request_uri; }
}
server {
    listen 443 ssl http2;
    server_name $hosts;
    ssl_certificate     /etc/letsencrypt/live/$d/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$d/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    if (\$host = www.$d) { return 301 https://$d\$request_uri; }
    location = / {
        proxy_pass http://$STOREFRONT/companies/$h;
        proxy_http_version 1.1;
        proxy_set_header Host autotorental.com;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $d;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    }
    location / {
        proxy_pass http://$STOREFRONT;
        proxy_http_version 1.1;
        proxy_set_header Host autotorental.com;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $d;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
    }
}
EOF
}

set_status() { psqlq "UPDATE seller SET custom_domain_status='$2', custom_domain_error=$3, updated_at=now() WHERE custom_domain='$1';"; }

# ---- 1) PROVISION: every domain not yet live whose DNS points here ----------
DESIRED=""   # space-separated list of desired domains for reconcile
while IFS='|' read -r domain handle st; do
  [ -z "$domain" ] && continue
  DESIRED="$DESIRED $domain"
  vhost="$SITES/${PREFIX}$domain.conf"
  # already live with a vhost present -> nothing to do
  if [ "$st" = "live" ] && [ -f "$vhost" ]; then continue; fi

  if ! resolves_here "$domain"; then
    log "skip $domain — DNS not pointing here yet"
    continue
  fi
  log "provisioning $domain (handle=$handle)"
  if [ "$DRY_RUN" = "--dry-run" ]; then log "  (dry-run) would run certbot + write vhost for $domain"; continue; fi

  cbhosts=(-d "$domain"); resolves_here "www.$domain" && cbhosts+=(-d "www.$domain")
  if certbot certonly --webroot -w "$WEBROOT" "${cbhosts[@]}" -n --agree-tos --email "$EMAIL" \
        --keep-until-expiring --expand >>"$LOG" 2>&1; then
    write_vhost "$domain" "$handle"
    if nginx_apply; then
      set_status "$domain" "live" "NULL"
      log "  -> LIVE: https://$domain"
    else
      rm -f "$vhost"; nginx -t >>"$LOG" 2>&1
      set_status "$domain" "error" "'nginx config test failed'"
      log "  -> ERROR: nginx -t failed for $domain, vhost reverted"
    fi
  else
    set_status "$domain" "error" "'certificate issuance failed — check DNS / rate limits'"
    log "  -> ERROR: certbot failed for $domain"
  fi
done < <(psqlq "SELECT custom_domain||'|'||COALESCE(handle,'')||'|'||COALESCE(custom_domain_status,'') FROM seller WHERE custom_domain IS NOT NULL AND deleted_at IS NULL;")

# ---- 2) RECONCILE: remove vhosts for domains no longer connected ------------
for f in "$SITES/${PREFIX}"*.conf; do
  [ -e "$f" ] || continue
  d="$(basename "$f" .conf)"; d="${d#$PREFIX}"
  case " $DESIRED " in *" $d "*) continue;; esac
  log "reconcile: removing orphaned vhost for $d"
  [ "$DRY_RUN" = "--dry-run" ] && { log "  (dry-run) would remove $f + cert"; continue; }
  bak="/tmp/${PREFIX}$d.conf.removed"; mv "$f" "$bak"
  if nginx_apply; then
    certbot delete --cert-name "$d" -n >>"$LOG" 2>&1 || true
    rm -f "$bak"; log "  -> removed $d"
  else
    mv "$bak" "$f"; nginx -t >>"$LOG" 2>&1; log "  -> revert: keeping $d (nginx -t failed without it)"
  fi
done

log "done."
