const T: Record<Locale, Partial<Record<TKey, string>>> = { en, ar, es, zh, th, ru, ur }

export function t(lang: Lang, key: TKey): string {
  const dict = T[lang] || T[DEFAULT_LOCALE]
  return (dict as any)[key] ?? (en as any)[key] ?? key
}

// Like t(), but interpolates {placeholders} from the vars map. Missing vars are
// left untouched. Used for templated SEO strings (e.g. "{n} cars available in {c}").
export function tf(lang: Lang, key: TKey, vars: Record<string, string | number>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}
